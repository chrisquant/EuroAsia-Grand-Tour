def _p(name, role="stay", lat=None, lon=None, arrive=None, until=None):
    src = next((s for s in STOPS if s["name"] == name), None)
    item = {
        "name": name,
        "lat": src["lat"] if lat is None else lat,
        "lon": src["lon"] if lon is None else lon,
        "role": role,
    }
    if role == "stay":
        item["arrive"] = arrive if arrive is not None else src["arrive"]
    if until is not None:
        item["until"] = until
    return item


