def country_by_id(cid):
    for c in COUNTRIES:
        if c["id"] == cid:
            return c
    raise KeyError(cid)


def _raw_total():
    return sum(s["leg_km"] for s in STOPS)


def scale():
    raw = _raw_total()
    return LOOP_KM / raw if raw else 1.0


def route_vertices(cities):
    """停留城市之间插入过路点，让总览的线跟着公路走。"""
    pts = []
    for i, city in enumerate(cities):
        pts.append(city)
        if i + 1 >= len(cities):
            continue
        for bend in ROUTE_BENDS.get((city["name"], cities[i + 1]["name"]), []):
            pts.append({**bend, "bend": True})
    return pts


def _km(a, b):
    from math import asin, cos, radians, sin, sqrt
    lat1, lon1, lat2, lon2 = (radians(x) for x in (a["lat"], a["lon"], b["lat"], b["lon"]))
    h = sin((lat2 - lat1) / 2) ** 2 + cos(lat1) * cos(lat2) * sin((lon2 - lon1) / 2) ** 2
    return 2 * 6371 * asin(sqrt(h))


def flat_cities():
    k = scale()
    rows = []
    cum = 0.0
    for s in STOPS:
        leg = round(s["leg_km"] * k)
        cum += leg
        c = country_by_id(s["country_id"])
        rows.append({
            **s,
            "country": c["name"],
            "leg_scaled": leg,
            "cum_km": cum,
            "color": COUNTRY_COLORS[s["country_id"]],
        })
    return rows


def visits(country):
    cities = flat_cities()
    runs, cur = [], []
    for c in cities:
        if c["country_id"] == country["id"]:
            cur.append(c)
        elif cur:
            runs.append(cur)
            cur = []
    if cur:
        runs.append(cur)
    if not runs:
        extra = cities_for(country)
        if extra:
            runs.append(extra)
    return runs


def cities_for(country):
    rows = [c for c in flat_cities() if c["country_id"] == country["id"]]
    if rows:
        return rows
    k = scale()
    out = []
    cum = 0
    for s in country.get("offroute", []):
        leg = round(s["leg_km"] * k)
        cum += leg
        out.append({
            **s,
            "country_id": country["id"],
            "country": country["name"],
            "leg_scaled": leg,
            "cum_km": cum,
            "color": COUNTRY_COLORS[country["id"]],
        })
    return out


def _lerp(a, b, t):
    return a + (b - a) * t


def _between(day, start, end):
    span = (end - start).days
    if span <= 0:
        return 0.0
    return max(0.0, min(1.0, (day - start).days / span))


def track_on(day):
    cities = flat_cities()
    first, last = cities[0], cities[-1]
    if day <= first["arrive"]:
        return {**first, "progress": 0.0, "along_km": 0}
    if day >= last["arrive"]:
        return {**last, "progress": 1.0, "along_km": last["cum_km"]}
    for i in range(len(cities) - 1):
        a, b = cities[i], cities[i + 1]
        if a["arrive"] <= day <= b["arrive"]:
            t = _between(day, a["arrive"], b["arrive"])
            cid = b["country_id"] if day >= b["arrive"] else a["country_id"]
            name = b["name"] if t > 0.98 else (a["name"] if t < 0.02 else f"{a['name']}→{b['name']}")
            path = [a, *ROUTE_BENDS.get((a["name"], b["name"]), []), b]
            spans = [_km(path[i], path[i + 1]) for i in range(len(path) - 1)]
            remain = t * (sum(spans) or 1)
            lat, lon = path[-1]["lat"], path[-1]["lon"]
            for i, span in enumerate(spans):
                if remain <= span or i == len(spans) - 1:
                    u = 0 if span <= 0 else max(0.0, min(1.0, remain / span))
                    lat = _lerp(path[i]["lat"], path[i + 1]["lat"], u)
                    lon = _lerp(path[i]["lon"], path[i + 1]["lon"], u)
                    break
                remain -= span
            return {
                "name": name,
                "lat": lat,
                "lon": lon,
                "country": country_by_id(cid)["name"],
                "country_id": cid,
                "progress": _lerp(a["cum_km"], b["cum_km"], t) / LOOP_KM,
                "along_km": _lerp(a["cum_km"], b["cum_km"], t),
                "color": COUNTRY_COLORS[cid],
            }
    return {**last, "progress": 1.0, "along_km": last["cum_km"]}


def daterange(start, end):
    d = start
    while d <= end:
        yield d
        d += timedelta(days=1)
